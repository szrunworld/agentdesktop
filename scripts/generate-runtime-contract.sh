#!/bin/bash
# Embed contracts/runtime/v1 in AgentDesktopProtocol as Swift string
# literals. Executables in the app bundle (the host and bin/agentdesktop)
# cannot find a SwiftPM resource bundle, so the contract travels in code.
# RuntimeContractTests fails when this file and the contracts differ; run
# this script after editing any file in contracts/runtime/v1.
set -euo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/Sources/AgentDesktopProtocol/RuntimeContractData.swift"
{
    echo "// Generated by scripts/generate-runtime-contract.sh from contracts/runtime/v1. Do not edit."
    echo
    echo "enum RuntimeContractData {"
    for name in runtime.schema methods errors; do
        var="$(echo "$name" | sed 's/\.schema$/Schema/')"
        echo "    static let $var = ##\"\"\""
        cat "$ROOT/contracts/runtime/v1/$name.json"
        echo "\"\"\"##"
        echo
    done
    echo "}"
} > "$OUT"
echo "wrote $OUT"
